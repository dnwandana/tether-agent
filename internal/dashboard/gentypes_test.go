type genInner struct {
	Name string `json:"name"`
}

type genSample struct {
	ID     int64           `json:"id"`
	Title  string          `json:"title,omitempty"`
	OK     bool            `json:"ok"`
	USD    float64         `json:"usd"`
	At     time.Time       `json:"at"`
	Tags   []string        `json:"tags"`
	Rows   [][]genInner    `json:"rows"`
	Next   *genInner       `json:"next"`
	Meta   map[string]int  `json:"meta"`
	Raw    json.RawMessage `json:"raw"`
	Data   any             `json:"data"`
	Skip   string          `json:"-"`
	hidden string
}

// genKind is a string type with registered values. The generator writes it as a union.
type genKind string

type genEnum struct {
	Kind  genKind   `json:"kind"`
	Kinds []genKind `json:"kinds"`
	Next  *genKind  `json:"next"`
}

func TestGenerateTypesShapes(t *testing.T) {
	_ = genSample{}.hidden
	got := generateTypes([]any{genSample{}, genInner{}, &genSample{}})
	want := `// Code generated by tether gen-dashboard-types. DO NOT EDIT.

export interface genInner {
  name: string;
}

export interface genSample {
  id: number;
  title?: string;
  ok: boolean;
  usd: number;
  at: string;
  tags: string[];
  rows: genInner[][];
  next: genInner | null;
  meta: Record<string, number>;
  raw: unknown;
  data: unknown;
}
`
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
	registerEnum(reflect.TypeFor[genKind](), "a", "b")
	t.Cleanup(func() { delete(enumValues, reflect.TypeFor[genKind]()) })
	got = generateTypes([]any{genEnum{}})
	want = `// Code generated by tether gen-dashboard-types. DO NOT EDIT.

export interface genEnum {
  kind: genKind;
  kinds: genKind[];
  next: genKind | null;
}

export type genKind = "a" | "b";
`
	if got != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
}

// The three setup states are the registered values, and the page type uses the union.
func TestSetupStateEnum(t *testing.T) {
	want := []string{"done", "open", "unknown"}
	got := enumValues[reflect.TypeFor[SetupState]()]
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("registered %q, want %q", got, want)
	}
	if string(SetupDone) != want[0] || string(SetupOpen) != want[1] || string(SetupUnknown) != want[2] {
		t.Fatal(SetupDone, SetupOpen, SetupUnknown)
	}
	text := GenerateTypes()
	for _, line := range []string{`export type SetupState = "done" | "open" | "unknown";`, "  state: SetupState;"} {
		if !strings.Contains(text, line) {
			t.Errorf("types.gen.ts has no line %q", line)
		}
	}
}

var genSnake = regexp.MustCompile(`^[a-z][a-z0-9_]*$`)

// Each field of each registered type has a snake_case json tag, so the JSON and the
// generated types agree.
func TestAPITypesTagged(t *testing.T) {
	if len(apiTypes) == 0 {
		t.Fatal("no registered API type")
	}
	seen := map[reflect.Type]bool{}
	var check func(rt reflect.Type)
	check = func(rt reflect.Type) {
		for rt.Kind() == reflect.Pointer || rt.Kind() == reflect.Slice || rt.Kind() == reflect.Array || rt.Kind() == reflect.Map {
			rt = rt.Elem()
		}
		if rt.Kind() != reflect.Struct || rt == reflect.TypeFor[time.Time]() || seen[rt] {
			return
		}
		seen[rt] = true
		for f := range rt.Fields() {
			if !f.IsExported() {
				continue
			}
			name, _, _ := strings.Cut(f.Tag.Get("json"), ",")
			if name == "-" {
				continue
			}
			if f.Anonymous && name == "" {
				check(f.Type)
				continue
			}
			if !genSnake.MatchString(name) {
				t.Errorf("%s.%s has the json name %q; give it a snake_case tag", rt.Name(), f.Name, name)
			}
			check(f.Type)
		}
	}
	for _, v := range apiTypes {
		check(reflect.TypeOf(v))
	}
}

