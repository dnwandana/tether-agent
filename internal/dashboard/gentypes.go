package dashboard

import (
	"encoding/json"
	"fmt"
	"reflect"
	"sort"
	"strings"
	"time"
)

// GenerateTypes returns web/src/api/types.gen.ts for the types that registerAPI collected.
func GenerateTypes() string { return generateTypes(apiTypes) }

// generateTypes returns the TypeScript text for the types of vs and of each struct that
// their fields name.
func generateTypes(vs []any) string {
	byName := map[string]reflect.Type{}
	body := map[string]string{}
	var pending []reflect.Type
	queue := func(rt reflect.Type) {
		if old, ok := byName[rt.Name()]; ok {
			if old != rt {
				panic("dashboard: two API types are named " + rt.Name())
			}
			return
		}
		byName[rt.Name()] = rt
		pending = append(pending, rt)
	}
	for _, v := range vs {
		rt := reflect.TypeOf(v)
		for rt != nil && rt.Kind() == reflect.Pointer {
			rt = rt.Elem()
		}
		if rt != nil && rt.Kind() == reflect.Struct && rt.Name() != "" {
			queue(rt)
		}
	}
	for len(pending) > 0 {
		rt := pending[0]
		pending = pending[1:]
		var b strings.Builder
		fmt.Fprintf(&b, "export interface %s {\n", rt.Name())
		writeFields(&b, rt, queue)
		b.WriteString("}\n")
		body[rt.Name()] = b.String()
	}
	names := make([]string, 0, len(body))
	for n := range body {
		names = append(names, n)
	}
	sort.Strings(names)
	parts := make([]string, len(names))
	for i, n := range names {
		parts[i] = body[n]
	}
	return "// Code generated by tether gen-dashboard-types. DO NOT EDIT.\n\n" + strings.Join(parts, "\n")
}

// writeFields writes the field lines of the struct rt. An embedded struct with no tag name
// puts its fields in place, as encoding/json does.
func writeFields(b *strings.Builder, rt reflect.Type, queue func(reflect.Type)) {
	for f := range rt.Fields() {
		tag := f.Tag.Get("json")
		name, opts, _ := strings.Cut(tag, ",")
		if tag == "-" {
			continue
		}
		if f.Anonymous && name == "" {
			et := f.Type
			if et.Kind() == reflect.Pointer {
				et = et.Elem()
			}
			if et.Kind() == reflect.Struct {
				writeFields(b, et, queue)
				continue
			}
		}
		if !f.IsExported() {
			continue
		}
		if name == "" {
			name = f.Name
		}
		opt := ""
		for o := range strings.SplitSeq(opts, ",") {
			if o == "omitempty" {
				opt = "?"
			}
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", name, opt, tsType(f.Type, queue))
	}
}

var (
	timeType = reflect.TypeFor[time.Time]()
	rawType  = reflect.TypeFor[json.RawMessage]()
)

// tsType returns the TypeScript type of rt and adds each named struct that it finds to
// the queue of interfaces.
func tsType(rt reflect.Type, queue func(reflect.Type)) string {
	switch rt {
	case timeType:
		return "string"
	case rawType:
		return "unknown"
	}
	switch rt.Kind() {
	case reflect.String:
		return "string"
	case reflect.Bool:
		return "boolean"
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		if rt.Kind() == reflect.Slice && rt.Elem().Kind() == reflect.Uint8 {
			return "string"
		}
		el := tsType(rt.Elem(), queue)
		if strings.Contains(el, " | ") {
			el = "(" + el + ")"
		}
		return el + "[]"
	case reflect.Map:
		return "Record<string, " + tsType(rt.Elem(), queue) + ">"
	case reflect.Pointer:
		return tsType(rt.Elem(), queue) + " | null"
	case reflect.Struct:
		if rt.Name() == "" {
			return "unknown"
		}
		queue(rt)
		return rt.Name()
	}
	return "unknown"
}
